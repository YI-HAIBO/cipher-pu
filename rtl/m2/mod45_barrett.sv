// mod45_barrett.sv  —  90 bit 输入 / 45 bit 常数模的 Barrett 快速归约
//
// 【2026-10-17 重建】原文件被误清空（2 字节），本文件依据：
//   (a) 唯一实例化点 rtl/m2/butterfly45_barrett_synth_top.sv:62-68 反推端口；
//   (b) 头部注释同类的 mod45_fastred.sv 交叉印证位宽约定。
//   原文件无法从 sim/*/ 副本恢复：全仓无任何非空副本，无 git，无 .bak。
//
// 端口签名（butterfly45_barrett_synth_top.sv:62-68 逐字确定）：
//   mod45_barrett #(
//       .Q_VALUE (Q_VALUE),              // 45'd17592186175489
//       .V_VALUE (46'd70368743653372)    // floor(2^90 / Q_VALUE)
//   ) u_mod (
//       .x (prod_raw),                   // [2*Q_WIDTH-1:0] = 90 bit
//       .r (prod_q)                      // [Q_WIDTH-1:0]  = 45 bit
//   );
//   纯组合，无时钟（与 mod45_fastred 同为「隔离出归约本身开销」的设计）。
//
// 数学（Barrett 归约，k = 45）：
//   预计算  V = floor(2^(2k) / Q) = floor(2^90 / Q)，46 bit
//     x < 2^90 时：
//       u  = x >> (k-1)          -> 46 bit
//       mu = floor(u*V / 2^(k+1))-> 46 bit,  mu <= floor(x/Q)
//       t  = x - mu*Q            -> 46 bit 量级,  t >= 0,  t < 2Q
//       r  = t mod Q             -> 2 次条件减即收敛
//   数学细节与上界证明见 scripts/_verify_barrett.py（暴力比对 x % Q）。
//
// 与 mod45_fastred 的定位差别（来自 butterfly45_barrett_synth_top.sv:1-14）：
//   本文件是 M2 规模可行性分析的 Barrett 对照件，用于量「Barrett 之后单蝴蝶
//   还剩多少 LUT」。生产路径 ntt_butterfly / poly_mult 用 mod45_fastred，
//   因为 fastred 把「乘 c」退化成移位+加、归约本体 0 DSP。
//=============================================================================

`timescale 1ns / 1ps

module mod45_barrett #(
    parameter logic [44:0] Q_VALUE = 45'd17592186175489,
    parameter logic [45:0] V_VALUE = 46'd70368743653372
) (
    input  wire logic [89:0] x,
    output wire logic [44:0] r
);

    localparam int K = 45;

    // =========================================================================
    // 步骤 1：u = x >> (K-1)   ->   46 bit
    // =========================================================================
    wire [45:0] u = x[89:44];

    // =========================================================================
    // 步骤 2：uv = u * V            46 x 46 = 92 bit
    //          mu = floor(uv / 2^(K+1)) = uv >> 46   ->   46 bit
    //          位宽铁律：n x m 的满积需 n+m bit，少 1 bit 会静默截高位。
    // =========================================================================
    wire [91:0] uv = u * V_VALUE;
    wire [45:0] mu = uv[91:46];

    // =========================================================================
    // 步骤 3：t = x - mu * Q
    //          mu < 2^46, Q < 2^45 -> mu*Q < 2^91，留 92 bit 容器
    //          mu <= floor(x/Q) 保证 t >= 0（Barrett 基本性质）
    // =========================================================================
    wire [91:0] muq = mu * Q_VALUE;
    wire [91:0] t   = {2'b0, x} - muq;

    // =========================================================================
    // 步骤 4：2 次条件减收敛到 [0, Q)
    //   Barrett 保证 t < 2Q，故 1 次减法已足够；写 2 次是给 Q 恰为
    //   2 的幂之类的边界留余量（本模数非 2 的幂，第二次恒不触发）。
    // =========================================================================
    wire [91:0] t0 = (t  >= {87'b0, Q_VALUE}) ? t  - {87'b0, Q_VALUE} : t;
    wire [91:0] t1 = (t0 >= {87'b0, Q_VALUE}) ? t0 - {87'b0, Q_VALUE} : t0;

    assign r = t1[44:0];

endmodule
