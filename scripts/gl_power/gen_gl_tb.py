#!/usr/bin/env python3
"""
gen_gl_tb.py -- M4/E30 step 2: generate gate-level testbench + omega tables + sim TCL.

Reads the funcsim netlist (out/gl_netlist.v) to enumerate the top module's
omega twiddle ports, then emits:
  sim_build/tb_gl_top.sv      -- gate-level TB (42 logic ports + 4096 omega ports)
  sim_build/omega_table.hex   -- omega^i mod q  (i = 0..N/2-1)
  sim_build/omega_inv_table.hex
  sim_build/sim.tcl           -- xsim TCL: open_saif_file / run all / close

Prod parameters (N=2^12): q=17592186175489, w=15163019180936, w_inv=7736254182915.
"""
import os
import re
import sys

PROJ = str(Path(__file__).resolve().parents[2])
GL = os.path.join(PROJ, "scripts", "gl_power")
NET = os.path.join(GL, "out", "gl_netlist.v")
SIM = os.path.join(GL, "sim_build")

Q = 17592186175489
W = 15163019180936
W_INV = 7736254182915
N = 4096
QW = 45
ACC_W = 106
ITER = 2


def main() -> int:
    os.makedirs(SIM, exist_ok=True)
    sim_fwd = SIM.replace(chr(92), "/")

    # ---- enumerate omega port indices from the netlist ----
    w_idx, wi_idx = set(), set()
    with open(NET, encoding="utf-8", errors="replace") as f:
        in_top = False
        for line in f:
            s = line.strip()
            if s.startswith("module e2e_ckks_mult_ctrl_m4"):
                in_top = True
                continue
            if in_top:
                if s.startswith("module ") or s == ");":
                    break
                m = re.match(r"input \[44:0\]\\(omega(?:_inv)?_table)\[(\d+)\]", s)
                if m:
                    (w_idx if m.group(1) == "omega_table" else wi_idx).add(int(m.group(2)))
    print(f"[gen] omega ports: {len(w_idx)} omega, {len(wi_idx)} omega_inv")
    assert len(w_idx) == N // 2 and len(wi_idx) == N // 2

    # ---- write omega tables (w^i mod q) ----
    def hex_line(val):
        return f"{val:0{QW // 4 + 1}x}"

    with open(os.path.join(SIM, "omega_table.hex"), "w") as f:
        v = 1
        for _ in range(N // 2):
            f.write(hex_line(v) + "\n")
            v = v * W % Q
    with open(os.path.join(SIM, "omega_inv_table.hex"), "w") as f:
        v = 1
        for _ in range(N // 2):
            f.write(hex_line(v) + "\n")
            v = v * W_INV % Q
    print(f"[gen] omega tables written ({N // 2} entries each)")

    # ---- emit TB ----
    lines = []
    a = lines.append
    a("// Gate-level TB for e2e_ckks_mult_ctrl_m4 funcsim netlist (M4/E30 SAIF)")
    a("// AUTO-GENERATED by gen_gl_tb.py -- do not hand-edit")
    a("`timescale 1ns / 1ps")
    a("`default_nettype none")
    a("module tb_gl_top;")
    a(f"    localparam N = {N};")
    a(f"    localparam QW = {QW};")
    a(f"    localparam ITER = {ITER};")
    a("")
    a("    logic clk = 1'b0;")
    a("    logic rst_n = 1'b0;")
    a("    always #5 clk = ~clk;  // 100 MHz")
    a("")
    a("    logic [2:0]  manual_gear;")
    a("    logic [2:0]  gear_sel;")
    a("    logic        start;")
    a("    logic        busy, done, error;")
    a("    logic        mode_sel, flush_valid_ext, hysteresis_en, manual_en, noise_mon_en;")
    a(f"    logic [{ACC_W-1}:0] energy_q2_ext;")
    a(f"    logic [{ACC_W-1}:0] energy_q2_int;")
    a("    logic        nm_flush_valid, nm_saturated;")
    a("    logic [53:0] nm_sample_count;")
    a("")
    a("    // six input streams: c0_1 c1_1 c0_2 c1_2 a b")
    a(f"    logic        in_valid [0:5];")
    a(f"    logic        in_ready [0:5];")
    a(f"    logic [{QW-1}:0] in_data [0:5];")
    a(f"    logic [{QW-1}:0] in_data_next [0:5];")
    a(f"    integer      in_idx [0:5];")
    a(f"    integer      ch;")
    a("    logic        sending;")
    a("")
    a("    // output streams: f0 f1")
    a("    logic        out_valid [0:1];")
    a("    logic        out_ready [0:1];")
    a(f"    logic [{QW-1}:0] out_data [0:1];")
    a("    integer      out_words = 0;")
    a("    integer      done_cnt = 0;")
    a("")
    a(f"    logic [{QW-1}:0] omega_table [0:{N // 2 - 1}];")
    a(f"    logic [{QW-1}:0] omega_inv_table [0:{N // 2 - 1}];")
    a("")
    a("    initial begin")
    a(f'        $readmemh("{sim_fwd}/omega_table.hex", omega_table);')
    a(f'        $readmemh("{sim_fwd}/omega_inv_table.hex", omega_inv_table);')
    a("    end")
    a("")
    a("    // ---- 64-bit LFSR for pseudo-random coefficient data ----")
    a("    logic [63:0] lfsr = 64'h5DEECE66D1234567;")
    a("    always_ff @(posedge clk) begin")
    a("        if (!rst_n) lfsr <= 64'h5DEECE66D1234567;")
    a("        else lfsr <= {lfsr[62:0], ~(lfsr[63] ^ lfsr[62])};")
    a("    end")
    a("")
    a("    // ---- input stream drivers ----")
    a("    always_ff @(posedge clk) begin")
    a("        if (!rst_n) begin")
    a("            for (ch = 0; ch < 6; ch = ch + 1) begin")
    a("                in_valid[ch] <= 1'b0;")
    a("                in_idx[ch]  <= 0;")
    a(f"                in_data[ch] <= {{{QW}{{1'b0}}}};")
    a("            end")
    a("        end else begin")
    a("            for (ch = 0; ch < 6; ch = ch + 1) begin")
    a("                if (sending) begin")
    a("                    in_valid[ch] <= (in_idx[ch] < N);")
    a("                    if (in_valid[ch] && in_ready[ch]) begin")
    a("                        in_idx[ch] <= in_idx[ch] + 1;")
    a(f"                        in_data[ch] <= lfsr[{QW-1}:0] ^ {QW}'h5A5A5A5A5;")
    a("                    end")
    a("                end else begin")
    a("                    in_valid[ch] <= 1'b0;")
    a("                end")
    a("            end")
    a("        end")
    a("    end")
    a("")
    a("    // ---- output consumers (always ready) ----")
    a("    always_comb out_ready[0] = 1'b1;")
    a("    always_comb out_ready[1] = 1'b1;")
    a("    always_ff @(posedge clk) begin")
    a("        if (rst_n) begin")
    a("            if (out_valid[0]) out_words <= out_words + 1;")
    a("            if (done) done_cnt <= done_cnt + 1;")
    a("        end")
    a("    end")
    a("")
    a("    // ---- master sequence ----")
    a("    integer it;")
    a("    initial begin")
    a("        gear_sel        = 3'd0;")
    a("        mode_sel        = 1'b1;  // adaptive gear control")
    a("        noise_mon_en    = 1'b1;  // internal noise monitoring")
    a("        hysteresis_en   = 1'b1;")
    a("        manual_en       = 1'b0;")
    a("        manual_gear     = 3'd0;")
    a(f"        energy_q2_ext   = {{{ACC_W}{{1'b0}}}};")
    a("        flush_valid_ext = 1'b0;")
    a("        start           = 1'b0;")
    a("        sending         = 1'b0;")
    a("        repeat (20) @(posedge clk);")
    a("        rst_n = 1'b1;")
    a("        repeat (10) @(posedge clk);")
    a("        for (it = 0; it < ITER; it = it + 1) begin")
    a("            // start pulse")
    a("            start = 1'b1;")
    a("            @(posedge clk);")
    a("            #1 start = 1'b0;")
    a("            sending = 1'b1;")
    a("            // wait for all six streams to drain")
    a("            wait (in_idx[0] >= N && in_idx[1] >= N && in_idx[2] >= N")
    a("                  && in_idx[3] >= N && in_idx[4] >= N && in_idx[5] >= N);")
    a("            sending = 1'b0;")
    a("            // wait for done")
    a("            wait (done_cnt > it);")
    a("        end")
    a("        repeat (50) @(posedge clk);")
    a("        $display(\"GLTB: done_cnt=%0d out_words=%0d\", done_cnt, out_words);")
    a("        $finish;")
    a("    end")
    a("")
    a("    // ---- watchdog ----")
    a("    initial begin")
    a("        #2000000;  // 2 ms")
    a('        $display("GLTB: TIMEOUT");')
    a("        $finish;")
    a("    end")
    a("")
    a("    // ---- VCD dump window (DUT only) ----")
    a("    initial begin")
    a(f'        #200; $dumpfile("{sim_fwd}/gl.vcd");')
    a("        $dumpvars(0, u_dut);")
    a("    end")
    a("")
    a("    // glbl is compiled as a standalone root so 'glbl.GSR' resolves")
    a("")
    a("    // ---- DUT: full port map ----")
    a("    e2e_ckks_mult_ctrl_m4 u_dut (")
    a("        .clk(clk),")
    a("        .rst_n(rst_n),")
    a("        .gear_sel(gear_sel),")
    a("        .mode_sel(mode_sel),")
    a("        .energy_q2_ext(energy_q2_ext),")
    a("        .flush_valid_ext(flush_valid_ext),")
    a("        .hysteresis_en(hysteresis_en),")
    a("        .manual_gear(manual_gear),")
    a("        .manual_en(manual_en),")
    a("        .noise_mon_en(noise_mon_en),")
    a("        .energy_q2_int(energy_q2_int),")
    a("        .nm_flush_valid(nm_flush_valid),")
    a("        .nm_sample_count(nm_sample_count),")
    a("        .nm_saturated(nm_saturated),")
    a("        .start(start),")
    a("        .busy(busy),")
    a("        .done(done),")
    a("        .error(error),")
    a("        .c0_1_valid(in_valid[0]), .c0_1_ready(in_ready[0]), .c0_1_data(in_data[0]),")
    a("        .c1_1_valid(in_valid[1]), .c1_1_ready(in_ready[1]), .c1_1_data(in_data[1]),")
    a("        .c0_2_valid(in_valid[2]), .c0_2_ready(in_ready[2]), .c0_2_data(in_data[2]),")
    a("        .c1_2_valid(in_valid[3]), .c1_2_ready(in_ready[3]), .c1_2_data(in_data[3]),")
    a("        .a_valid(in_valid[4]),    .a_ready(in_ready[4]),    .a_data(in_data[4]),")
    a("        .b_valid(in_valid[5]),    .b_ready(in_ready[5]),    .b_data(in_data[5]),")
    a("        .f0_valid(out_valid[0]), .f0_ready(out_ready[0]), .f0_data(out_data[0]),")
    a("        .f1_valid(out_valid[1]), .f1_ready(out_ready[1]), .f1_data(out_data[1])")
    for i in sorted(w_idx):
        a(f"        ,.\\omega_table[{i}] (omega_table[{i}])")
    for i in sorted(wi_idx):
        a(f"        ,.\\omega_inv_table[{i}] (omega_inv_table[{i}])")
    a("    );")
    a("")
    a("endmodule")
    tb_path = os.path.join(SIM, "tb_gl_top.sv")
    with open(tb_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"[gen] TB -> {tb_path} ({len(lines)} lines)")

    # ---- xsim TCL ----
    tcl = (
        "open_saif_file " + (os.path.join(GL, "out", "sim.saif").replace("\\", "/")) + "\n"
        "run all\n"
        "close_saif_file\n"
        "exit\n"
    )
    with open(os.path.join(SIM, "sim.tcl"), "w") as f:
        f.write(tcl)
    print(f"[gen] sim.tcl -> {SIM}\\sim.tcl")
    return 0


if __name__ == "__main__":
    sys.exit(main())
