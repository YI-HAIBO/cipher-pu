# -*- coding: utf-8 -*-
"""M3-a：从模数链 JSON 生成 K 组 omega_table。

用法：
    python gen_omega_tables_chain.py --chain-file rtl/m2/modulus_chain_chain4.json --outdir rtl/m2/
    python gen_omega_tables_chain.py --verify-only --outdir rtl/m2/

输出（对每个素数 qi）：
    omega_table_chain4_q{i}.hex         正 omega 表（N/2 项）
    omega_inv_table_chain4_q{i}.hex     逆 omega 表（N/2 项）
    omega_table_chain4_q{i}.sv.h        SystemVerilog 头文件
    omega_table_chain4_q{i}.verify.txt  校验报告
"""
from __future__ import annotations

import argparse
import io
import json
import sys
from pathlib import Path

# 导入 gen_omega_tables 的验证函数
sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_omega_tables import (
    generate_table,
    verify,
    format_sv_header,
    format_hex,
)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--chain-file", default="rtl/m2/modulus_chain_chain4.json")
    ap.add_argument("--outdir", default=None, help="输出目录（默认与 chain_file 同目录）")
    ap.add_argument("--verify-only", action="store_true")
    ap.add_argument("--tag-suffix", default="chain4", help="输出文件中的 tag 后缀")
    args = ap.parse_args()

    chain_path = Path(args.chain_file)
    with io.open(chain_path, "r", encoding="utf-8") as f:
        chain = json.load(f)

    outdir = Path(args.outdir) if args.outdir else chain_path.parent
    outdir.mkdir(parents=True, exist_ok=True)

    tag = args.tag_suffix
    N = chain[0]["N"]
    Q_WIDTH = chain[0]["q_bits"]

    print(f"[INFO] 从 {chain_path} 加载 K={len(chain)} 模数链")
    print(f"[INFO] N = {N}, Q_WIDTH = {Q_WIDTH}")
    print(f"[INFO] 输出目录：{outdir}")
    print()

    all_ok = True
    for i, p in enumerate(chain):
        q = p["q"]
        omega = p["omega"]
        omega_inv = p["omega_inv"]
        c = p["c"]
        print(f"[{i}] q = {q}  (c = {c})  omega = {omega}")

        # 生成表
        omega_table = generate_table(omega, q, N)
        omega_inv_table = generate_table(omega_inv, q, N)

        # 校验
        errs = verify(N, q, omega, omega_inv, omega_table, omega_inv_table)
        if errs:
            print(f"  [FAIL] 校验失败：")
            for e in errs:
                print(f"    - {e}")
            all_ok = False
            continue
        print(f"  [OK] 全部校验通过")

        if args.verify_only:
            continue

        # 写文件
        for name, values in [
            ("omega_table", omega_table),
            ("omega_inv_table", omega_inv_table),
        ]:
            hex_path = outdir / f"{name}_{tag}_q{i}.hex"
            hex_path.write_text(format_hex(values, Q_WIDTH), encoding="utf-8")

        # .sv.h 头文件（合并 omega_table 与 omega_inv_table）
        sv_h_path = outdir / f"omega_table_{tag}_q{i}.sv.h"
        header = format_sv_header(f"{tag}_q{i}", Q_WIDTH, q, omega, omega_inv,
                                  omega_table, omega_inv_table)
        sv_h_path.write_text(header, encoding="utf-8")

        # verify.txt 报告
        verify_lines = [
            f"# omega_table_{tag}_q{i} verification report",
            f"# Generated by scripts/gen_omega_tables_chain.py",
            f"",
            f"N           = {N}    (2^{N.bit_length()-1})",
            f"q           = {q}    ({Q_WIDTH}-bit prime)",
            f"c           = {c}    (q - 2^{Q_WIDTH-1})",
            f"omega       = {omega}",
            f"omega_inv   = {omega_inv}",
            f"N_INV       = {p['N_INV']}",
            f"",
            f"# omega^N mod q = {pow(omega, N, q)}   (expected 1)   "
            f"{'[OK]' if pow(omega, N, q) == 1 else '[FAIL]'}",
            f"# omega*omega_inv mod q = {(omega * omega_inv) % q}   (expected 1)   "
            f"{'[OK]' if (omega * omega_inv) % q == 1 else '[FAIL]'}",
            f"# N * N_INV mod q = {(N * p['N_INV']) % q}   (expected 1)   "
            f"{'[OK]' if (N * p['N_INV']) % q == 1 else '[FAIL]'}",
            f"# (NTT ∘ INTT) = identity on 3 random polynomials",
            f"# Table size: {len(omega_table)} entries (indices 0..{len(omega_table)-1})",
            f"",
            f"# First 8 entries of omega_table:",
        ]
        for k, v in enumerate(omega_table[:8]):
            verify_lines.append(f"  [{k:3d}] = {v}")
        verify_lines.append(f"# ... (total {len(omega_table)} entries)")

        verify_path = outdir / f"omega_table_{tag}_q{i}.verify.txt"
        verify_path.write_text("\n".join(verify_lines) + "\n", encoding="utf-8")

        print(f"  [WRITE] {hex_path.name}, omega_inv_table_{tag}_q{i}.hex, "
              f"{sv_h_path.name}, {verify_path.name}")
        print()

    if not all_ok:
        print(f"[FAIL] 至少一个素数校验失败", file=sys.stderr)
        return 3

    print(f"[DONE] 全部 {len(chain)} 组 omega_table 已生成")
    return 0


if __name__ == "__main__":
    sys.exit(main())
